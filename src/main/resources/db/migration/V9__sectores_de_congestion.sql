-- RF-09 (SCRUM-18): sectores de la ciudad con congestion historica conocida.
--
-- El trancon se registra por SECTOR y no por ruta: si la Carrera 1 se tranca a las
-- 5 de la tarde, lo sufre cualquier buseta que pase por ahi. Registrarlo por ruta
-- obligaria a repetir la misma ventana en cada una y a mantenerlas sincronizadas.
--
-- La ventana son dos horas y no un booleano: el aviso se enciende 30 min antes de
-- start_time y se apaga al llegar a end_time, calculo que un bool no sostiene.
--
-- Sin columna de dia de la semana: este semestre la misma ventana rige todos los
-- dias. Es una limitacion de alcance declarada en la historia, no un olvido; cuando
-- deje de alcanzar, entra como migracion nueva.
CREATE TABLE traffic_sectors (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(140) NOT NULL,
    start_time TIME         NOT NULL,
    end_time   TIME         NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_traffic_sectors_name UNIQUE (name)
);

-- Barrios que caen dentro del sector. Se cruza por NOMBRE contra route_neighborhoods,
-- igual que ya hace la busqueda de ruta: en Fusagasuga no hay paradas formales ni
-- catalogo de barrios con id propio, el nombre es el identificador que maneja el
-- usuario y el que viene en la semilla de rutas.
CREATE TABLE traffic_sector_neighborhoods (
    sector_id         BIGINT       NOT NULL,
    neighborhood_name VARCHAR(120) NOT NULL,
    PRIMARY KEY (sector_id, neighborhood_name),
    CONSTRAINT fk_traffic_sector_neighborhoods_sector
        FOREIGN KEY (sector_id) REFERENCES traffic_sectors (id) ON DELETE CASCADE
);

-- Se consulta "que sectores tocan estos barrios", asi que el indice va por nombre.
CREATE INDEX idx_traffic_sector_neighborhoods_name
    ON traffic_sector_neighborhoods (neighborhood_name);

