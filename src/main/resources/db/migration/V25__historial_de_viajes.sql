-- V25 — Historial de viajes "Ya me subi" (SCRUM-9, P4).
--
-- Flyway es el dueno del esquema. Las migraciones ya aplicadas NO se tocan.
--
-- Es distinto del historial de BUSQUEDAS (search_history, V17): una busqueda es
-- una pregunta; un viaje es lo que el usuario confirmo haber tomado al tocar
-- "Ya me subi". El viaje mas reciente da el "ultimo destino al que fuiste".
--
-- Sin datos personales nuevos: no se guarda la ubicacion del usuario, solo el
-- destino que eligio y la etiqueta de origen que se mostro en la busqueda.
--
-- destination_place_id NO lleva FK a places: esa tabla la crea otra rama en
-- paralelo (P1). Se guarda solo el id; si el destino fue un punto del mapa, va NULL.
--
-- El tope de 10 viajes por usuario lo impone la aplicacion en la misma
-- transaccion del INSERT (RidePersistenceAdapter.saveKeepingLatest), igual que
-- el tope de 6 de search_history.
CREATE TABLE ride_history (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    route_id             BIGINT           NOT NULL REFERENCES routes(id),
    destination_label    VARCHAR(120)     NOT NULL,
    destination_place_id BIGINT,
    destination_lat      DOUBLE PRECISION NOT NULL,
    destination_lng      DOUBLE PRECISION NOT NULL,
    origin_label         VARCHAR(120)     NOT NULL,
    boarded_at           TIMESTAMPTZ      NOT NULL DEFAULT now()
);

COMMENT ON TABLE ride_history IS
    'Ultimos viajes confirmados con Ya me subi, por usuario. Tope de 10 por usuario, recortado por la aplicacion.';
COMMENT ON COLUMN ride_history.destination_place_id IS
    'Id del lugar del catalogo si el destino fue uno; NULL si fue un punto del mapa. Sin FK a proposito.';

-- Sostiene la lectura de los 10 mas recientes y la subconsulta del recorte;
-- id DESC desempata dos viajes en el mismo instante.
CREATE INDEX ix_ride_history_user_boarded
    ON ride_history (user_id, boarded_at DESC, id DESC);
