-- SCRUM-8 / P1: congestion por CIRCULO y velocidades observadas por ruta.
--
-- 1. traffic_sectors gana centro y radio. Un sector con circulo aplica cuando el TRAMO que el usuario
--    recorre en la buseta (de su abordaje a su bajada) pasa a menos de radius_m metros del centro; los
--    barrios de traffic_sector_neighborhoods dejan de ser el criterio para esos sectores. Las columnas
--    son NULLABLE para no romper filas viejas: un sector sin circulo sigue cruzandose por nombre de barrio.
--
-- 2. Las dos filas del Indio (V20) reciben como centro el lugar canonico "Monumento El Indio" (V21) y
--    450 m de radio, decision de Santiago del 2026-11-08. Franjas 12:00-14:00 y 17:00-19:00, todos los
--    dias, aviso desde 30 min antes: eso ya lo siembra V20 y no cambia.
--
-- 3. route_speed_observations guarda la velocidad que Google (con trafico) midio para el tramo de cada
--    busqueda. La mediana de las ultimas 50 de una ruta (minimo 5 muestras) reemplaza a la velocidad
--    fija de 15 km/h (urbana) o 30 km/h (intermunicipal) al rankear.
ALTER TABLE traffic_sectors
    ADD COLUMN center_lat DOUBLE PRECISION,
    ADD COLUMN center_lng DOUBLE PRECISION,
    ADD COLUMN radius_m   INTEGER,
    ADD CONSTRAINT ck_traffic_sectors_circle CHECK (
        (center_lat IS NULL AND center_lng IS NULL AND radius_m IS NULL)
        OR (center_lat BETWEEN -90 AND 90 AND center_lng BETWEEN -180 AND 180 AND radius_m > 0));

UPDATE traffic_sectors ts
   SET center_lat = p.lat,
       center_lng = p.lng,
       radius_m   = 450,
       updated_at = now()
  FROM places p
 WHERE p.slug = 'monumento-el-indio'
   AND ts.name IN ('Indio (mediodia)', 'Indio (tarde)');

CREATE TABLE route_speed_observations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id     BIGINT        NOT NULL,
    observed_kmh NUMERIC(6, 2) NOT NULL,
    observed_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_route_speed_observations_route FOREIGN KEY (route_id) REFERENCES routes (id) ON DELETE CASCADE,
    CONSTRAINT ck_route_speed_observations_kmh CHECK (observed_kmh > 0 AND observed_kmh <= 120)
);

CREATE INDEX idx_route_speed_observations_route_time
    ON route_speed_observations (route_id, observed_at DESC);
