-- SCRUM-25 (RF-12): suspension temporal de una ruta con ventana de tiempo.
--
-- Es distinta del soft delete de V27 (INACTIVA): la ruta sigue existiendo y VUELVE SOLA cuando
-- termina la ventana. Por eso routes.status no cambia: no hay scheduler (el tier gratis de Render se
-- duerme a los 15 min y un job que cambiara el estado se perderia). Una ruta esta efectivamente
-- suspendida si existe una fila con starts_at <= ahora < ends_at y lifted_at IS NULL; esa condicion
-- vive en una sola consulta del adaptador de persistencia.
--
-- lifted_at lo fija el administrador al reactivar a mano antes del fin; la fila se conserva como
-- historial en vez de borrarse.
CREATE TABLE route_suspensions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id   BIGINT       NOT NULL REFERENCES routes(id) ON DELETE CASCADE,
    starts_at  TIMESTAMPTZ  NOT NULL,
    ends_at    TIMESTAMPTZ  NOT NULL,
    reason     VARCHAR(200),
    -- Quien la creo. Nulo si esa cuenta se borra: la suspension no debe impedirlo.
    created_by BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    lifted_at  TIMESTAMPTZ,
    CONSTRAINT ck_route_suspensions_window CHECK (ends_at > starts_at)
);

COMMENT ON TABLE route_suspensions IS
    'Ventanas de suspension temporal de rutas (RF-12). Vigente = starts_at <= now < ends_at y lifted_at IS NULL.';
COMMENT ON COLUMN route_suspensions.lifted_at IS
    'Instante en que el administrador reactivo la ruta a mano; NULL si no se ha levantado.';

CREATE INDEX ix_route_suspensions_route_window
    ON route_suspensions (route_id, starts_at, ends_at);
