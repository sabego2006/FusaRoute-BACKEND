-- V24 — Logs de la aplicacion y eventos de uso en la base (SCRUM-186).
--
-- Flyway es el dueno del esquema. Las migraciones ya aplicadas NO se tocan: editar
-- una migracion ya aplicada cambia su checksum y rompe el arranque.
--
-- Permisos: no hay GRANT a proposito. Flyway corre con el rol de la aplicacion
-- (fusaroute_dev / fusaroute_prod, nunca el superusuario), asi que ese rol queda como
-- DUENO de las dos tablas y de sus secuencias, y un dueno no necesita permisos
-- adicionales. Un GRANT aqui nombraria un rol concreto y romperia el mismo archivo en
-- el otro ambiente.
--
-- Presupuesto de espacio: el plan gratis de Supabase da 500 MB para todo el proyecto.
-- Por eso las dos tablas se purgan a 30 dias (ver MonitoringDataPurger) y los textos
-- largos llevan un tope en la columna: el escritor ya los recorta, y el VARCHAR es la
-- red de seguridad si alguien inserta a mano.


-- ---------------------------------------------------------------------------
-- app_logs — todo WARN y ERROR de la aplicacion, mas una fila INFO de arranque
-- ---------------------------------------------------------------------------
-- Sin FK a users y sin columna de usuario: un log no debe poder reconstruir quien
-- hizo que. El mensaje pasa antes por LogSanitizer, que quita llaves, JWT, contrasenas
-- y el encabezado Authorization.
CREATE TABLE app_logs (
    id        BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Instante en que ocurrio el evento, no en que se escribio: el escritor es
    -- asincrono y un lote puede salir segundos despues.
    ts        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    level     VARCHAR(10)   NOT NULL,
    CONSTRAINT ck_app_logs_level CHECK (level IN ('INFO', 'WARN', 'ERROR')),

    logger    VARCHAR(255)  NOT NULL,
    message   VARCHAR(2000) NOT NULL,

    -- Pila de la excepcion, recortada a 4000 caracteres. NULL si el log no trae una.
    exception VARCHAR(4000),

    thread    VARCHAR(255),

    -- Perfil activo de Spring (dev, pre, prod) al momento de escribir.
    profile   VARCHAR(50)
);

COMMENT ON TABLE app_logs IS
    'WARN y ERROR de la aplicacion y una fila INFO por arranque (SCRUM-186). Escritura asincrona; se purga a 30 dias.';
COMMENT ON COLUMN app_logs.ts IS
    'Cuando ocurrio el evento, no cuando se escribio la fila.';
COMMENT ON COLUMN app_logs.message IS
    'Mensaje ya sanitizado (sin llaves, JWT, contrasenas ni Authorization) y recortado a 2000.';
COMMENT ON COLUMN app_logs.exception IS
    'Pila recortada a 4000 caracteres y sanitizada. NULL si el log no lleva excepcion.';

-- Los dos accesos reales: "lo ultimo que paso" (GET /api/admin/logs y la consulta de
-- la sustentacion) y "lo ultimo de nivel X". El indice por ts DESC tambien sirve a la
-- purga, que filtra por ts < corte.
CREATE INDEX ix_app_logs_ts ON app_logs (ts DESC);
CREATE INDEX ix_app_logs_level_ts ON app_logs (level, ts DESC);


-- ---------------------------------------------------------------------------
-- search_events — una fila por busqueda de ruta y por toque de "Ya me subi"
-- ---------------------------------------------------------------------------
-- SIN IP y SIN id de usuario, a proposito: sirve para medir el uso del sistema
-- (cuantas busquedas, a que hora, con que resultado), no para seguir a una persona.
-- Los nombres de origen y destino son barrios del catalogo, no direcciones.
--
-- route_id es columna suelta, sin FK: es dato de analitica y debe sobrevivir a que
-- la ruta se borre o se renumere.
CREATE TABLE search_events (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts                TIMESTAMPTZ  NOT NULL DEFAULT now(),

    event_type        VARCHAR(10)  NOT NULL,
    CONSTRAINT ck_search_events_type CHECK (event_type IN ('SEARCH', 'BOARDED')),

    origin_label      VARCHAR(120),
    destination_label VARCHAR(120),
    route_id          BIGINT,

    outcome           VARCHAR(15)  NOT NULL,
    CONSTRAINT ck_search_events_outcome CHECK (outcome IN ('FOUND', 'LONG_WALK', 'NOT_FOUND', 'ERROR')),

    -- De donde salio el tiempo estimado: del trafico real de Google (TRAFFIC) o de
    -- la estimacion propia (ESTIMATED). NULL si no hubo ruta o no hay tiempo.
    eta_source        VARCHAR(10),
    CONSTRAINT ck_search_events_eta CHECK (eta_source IS NULL OR eta_source IN ('TRAFFIC', 'ESTIMATED')),

    latency_ms        INTEGER      CHECK (latency_ms IS NULL OR latency_ms >= 0),

    -- Si la ruta elegida iba por un tramo con ventana de congestion activa.
    congestion        BOOLEAN      NOT NULL DEFAULT FALSE
);

COMMENT ON TABLE search_events IS
    'Una fila por busqueda de ruta y por toque de "Ya me subi" (SCRUM-186). Sin IP ni usuario. Se purga a 30 dias.';
COMMENT ON COLUMN search_events.outcome IS
    'FOUND, LONG_WALK (hay ruta pero la caminata es larga), NOT_FOUND o ERROR.';
COMMENT ON COLUMN search_events.eta_source IS
    'TRAFFIC (Google con trafico) o ESTIMATED (estimacion propia). NULL si no hubo tiempo.';

CREATE INDEX ix_search_events_ts ON search_events (ts DESC);
