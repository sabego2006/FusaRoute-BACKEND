-- ---------------------------------------------------------------------------
-- feedback — un comentario del usuario y la respuesta del administrador (RF-08/RF-14)
-- ---------------------------------------------------------------------------
-- La tabla se llama feedback y no comments porque es el nombre del modelo de dominio
-- que fija el CLAUDE.md del repo. Los endpoints si son /api/comments: el usuario
-- habla de "comentarios", y la URL es lenguaje de usuario.
--
-- user_id es columna suelta con FK y no una asociacion JPA, igual que en
-- search_history (V17) y favorite_destination (V18): el listado solo necesita el id
-- para filtrar y no el usuario entero en cada lectura.
--
-- ON DELETE CASCADE: el comentario no sobrevive a la cuenta que lo escribio. Es
-- consistente con el historial y el favorito, y es lo que corresponde cuando el
-- criterio de aceptacion dice que el comentario esta "vinculado al perfil": sin
-- perfil no hay a quien atribuirlo, y un comentario huerfano en el panel del
-- administrador no se puede responder.
CREATE TABLE feedback (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    -- author_name es una COPIA del nombre del perfil al momento de escribir, no una
    -- lectura en vivo por la FK. El criterio pide que el comentario muestre el nombre
    -- de quien lo escribio; si se leyera del perfil en cada consulta, un cambio de
    -- nombre reescribiria de forma retroactiva comentarios de hace meses y la
    -- respuesta del administrador quedaria dirigida a alguien que ya no existe con ese
    -- nombre. 120 es el mismo ancho que users.name.
    author_name VARCHAR(120) NOT NULL,

    -- 100 es el maximo del criterio de aceptacion de RF-08, declarado tambien en
    -- Feedback.MAX_TEXT_LENGTH y en el @Column de la entidad. Hibernate valida el tipo
    -- al arrancar (ddl-auto=validate), asi que los tres deben coincidir.
    text        VARCHAR(100) NOT NULL,

    -- El CHECK de longitud repite en la base la regla que ya vive en el dominio. No es
    -- redundancia por desconfianza del codigo: el VARCHAR(100) solo ataja el maximo, y
    -- el minimo de 10 no tiene como expresarse en el tipo. Dejarlo solo en Java
    -- significaria que una carga de datos a mano o un script de siembra puede meter un
    -- comentario de dos letras que despues ninguna pantalla sabe por que paso.
    CONSTRAINT ck_feedback_text_length CHECK (char_length(trim(text)) BETWEEN 10 AND 100),

    status      VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    CONSTRAINT ck_feedback_status CHECK (status IN ('PENDING', 'ANSWERED')),

    -- 500 para la respuesta, mas holgado que el comentario: el usuario pide algo en
    -- una linea, pero explicar por que una ruta no pasa por un barrio toma varias.
    reply       VARCHAR(500),
    answered_at TIMESTAMPTZ,

    -- Coherencia del estado, en la base y no solo en el dominio: una fila ANSWERED sin
    -- respuesta no se puede pintar, y una PENDING con respuesta mentiria al conteo de
    -- pendientes del panel de RF-13. El dominio ya lo valida; aqui se vuelve
    -- imposible, que es distinto.
    CONSTRAINT ck_feedback_reply_coherente CHECK (
        (status = 'PENDING'  AND reply IS NULL     AND answered_at IS NULL)
        OR
        (status = 'ANSWERED' AND reply IS NOT NULL AND answered_at IS NOT NULL)
    ),

    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE feedback IS
    'Comentarios de los usuarios y la respuesta del administrador (RF-08 y RF-14). Una sola respuesta por comentario, no hilo.';
COMMENT ON COLUMN feedback.author_name IS
    'Nombre del autor COPIADO al escribir, no leido del perfil: un cambio de nombre no debe reescribir comentarios viejos.';
COMMENT ON COLUMN feedback.status IS
    'PENDING o ANSWERED. Mientras este PENDING el autor puede editar y borrar; es el mismo estado que cuenta la metrica 4 de RF-13.';
COMMENT ON COLUMN feedback.reply IS
    'Respuesta del administrador. NULL mientras este pendiente. Corregirla reescribe esta columna, nunca agrega una fila.';
COMMENT ON COLUMN feedback.answered_at IS
    'Cuando se respondio. Se reescribe al corregir la respuesta, para que el contador de respuestas nuevas vuelva a avisar.';
COMMENT ON COLUMN feedback.updated_at IS
    'Ultima escritura sobre la fila, sea del autor al editar o del administrador al responder.';


-- Indice del listado del administrador (SCRUM-98) y de la metrica 4 de RF-13.
--
-- El orden de las columnas es (status, created_at) porque las dos consultas que lo
-- usan arrancan filtrando o agrupando por status: "pendientes primero" y "cuantos
-- pendientes hay". Con created_at primero, el conteo de pendientes tendria que
-- recorrer toda la tabla.
--
-- created_at va DESC porque el listado muestra lo mas reciente arriba dentro de cada
-- estado, y asi se lee en el orden del indice sin un sort aparte.
CREATE INDEX ix_feedback_status_created
    ON feedback (status, created_at DESC);

-- Indice del listado del propio usuario (GET /api/comments/me), que es la consulta
-- mas frecuente de la tabla: una por visita a la pantalla de comentarios.
CREATE INDEX ix_feedback_user_created
    ON feedback (user_id, created_at DESC);


-- ---------------------------------------------------------------------------
-- users — registro de los dos ultimos ingresos (SCRUM-101)
-- ---------------------------------------------------------------------------
-- SON DOS COLUMNAS Y NO UNA, y la razon es la pregunta que tienen que responder:
-- "que me respondieron desde la ultima vez que entre".
--
-- Con una sola columna la respuesta es siempre "nada". El login exitoso mueve
-- last_login_at a now(), y el frontend consulta el contador justo despues de iniciar
-- sesion, asi que comparar answered_at > last_login_at compara contra un instante que
-- acaba de ocurrir. El contador daria cero para todo el mundo, siempre, y el defecto
-- no se veria en ninguna prueba que no mire el reloj.
--
-- Por eso el login CORRE el valor: lo que era last_login_at pasa a previous_login_at
-- y now() queda como last_login_at. El contador compara contra previous_login_at.
--
-- Las dos son NULL mientras el usuario no haya iniciado sesion nunca. previous_login_at
-- en NULL significa "primer ingreso, no hay un antes": el contador devuelve 0 en vez
-- de contar todo el historial de la cuenta.
--
-- Nullable y sin DEFAULT a proposito: un DEFAULT now() en el ALTER le inventaria a
-- todos los usuarios ya registrados un ingreso que nunca ocurrio.
ALTER TABLE users
    ADD COLUMN last_login_at     TIMESTAMPTZ,
    ADD COLUMN previous_login_at TIMESTAMPTZ;

COMMENT ON COLUMN users.last_login_at IS
    'Ultimo ingreso exitoso. Dato de auditoria; lo escribe el login y la confirmacion de TOTP, que tambien deja sesion abierta.';
COMMENT ON COLUMN users.previous_login_at IS
    'Ingreso exitoso anterior al ultimo. Es el instante contra el que se cuentan las respuestas nuevas de RF-14 (SCRUM-101).';
