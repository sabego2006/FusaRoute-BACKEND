-- a partir de 41 fotos de campo del 27-sep-2026 (SCRUM-174). Esta migracion siembra
-- SOLO los 10 letreros con evidencia de texto suficiente para identificar la ruta sin
-- adivinar — el resto del trabajo de ese flujo (Santiago + Claude, confirmado par por
-- par) quedo fuera a proposito, dicho abajo.
--
-- OJO, dicho explicito para que nadie lo descubra tarde:
--
-- 1. De las 9 rutas sembradas hasta V9 (origin/main), solo 6 quedan con letrero.
--    'Fusagasugá - Pasca', 'Gran Colombia' y 'Villa Leny - SENA Quebrajacho' NO
--    tienen ningun letrero fotografiado: ninguna de las 29 placas modeladas dice
--    PASCA, ALASKA, GRAN COLOMBIA, VILLA LENY, VILLA NATALIA, SENA ni QUEBRAJACHO.
--    La API para esas tres devuelve una lista vacia de letreros, no uno inventado.
--
-- 2. De los 29 letreros modelados en SCRUM-175, 19 quedan SIN sembrar aqui: son de
--    rutas que no existen en el catalogo (Nariño Pekin, Villa Patricia, Cuja -
--    Horizonte, La Palma, Caney, El Eden, Palacios - Trinidad - Guavio, y otros).
--    Cerrar esa brecha es trabajo de campo nuevo, no de este issue.
--
-- 3. 'Camino Real - La Pampa' tiene TRES letreros en dos sentidos (uno SUBIENDO,
--    dos BAJANDO) porque asi quedo la evidencia de campo: dos busetas distintas
--    muestran la misma tabla BAJANDO con una primera linea distinta ("HOSPITAL" vs
--    "U. HOSPITAL"). Se sembraron las dos en vez de descartar una.
--
-- 4. Los colores de route_sign_lines estan ESTIMADOS A OJO sobre la foto, sin
--    gotero ni medicion. El letrero que pinte el frontend se parecera al real, no
--    sera una reproduccion exacta.
--
-- 5. line_role queda NULL en toda la semilla: el dato de campo no etiqueta que
--    linea es "principal" ni "secundaria" (eso solo existe como regla de estilo
--    por plantilla en letreros-estilos.json -> templates, no por letrero). La
--    columna se deja para cuando ese etiquetado se levante, no se infiere aqui.
--
-- 6. El codigo de placa (P-10, P-15, P-12...) NO identifica la ruta: el mismo
--    codigo aparece en letreros de rutas distintas (P-15 esta en LC-001, LC-007 y
--    LC-018 con texto diferente). Por eso el emparejamiento de abajo se hizo por
--    el TEXTO completo de las placas, no por el codigo.
--
-- Emparejamiento sembrado (ruta <- letrero, confianza y evidencia resumidas;
-- el detalle completo del analisis esta en el plan de la sesion, no en este
-- archivo):
--
--   Llano Largo - La Clarita ("100")                 <- LC-029 (arco, codigo "100",
--                                                         texto igual a foto publica
--                                                         de 2022) + LC-022 (P-10,
--                                                         "...LLANO LARGO", 2o letrero)
--   Maiz Amarillo                                     <- LC-018 (P-15, el mismo
--                                                         letrero del que V5 saco
--                                                         los barrios)
--   Pablo Bello - Cedritos                            <- LC-027 (P-20, unico letrero
--                                                         que dice CEDRITOS)
--   Camino Real - La Pampa                            <- LC-008 (SUBIENDO) + LC-015
--                                                         y LC-021 (BAJANDO, dos
--                                                         busetas)
--   Fusagasugá - Chinauta (Inspección El Triunfo)     <- LC-012 (codigo 74,
--                                                         Boqueron) + LC-013
--                                                         (codigo 03, Escuela)
--   Fusagasugá - Arbeláez                             <- LC-025 (unico letrero que
--                                                         dice ARBELAEZ)
--
-- field_id (LC-0NN) es la trazabilidad: permite volver de una fila de la base a su
-- entrada en letreros-estilos.json y a la foto original en docs/fotos-letreros/.

CREATE TABLE route_signs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id      BIGINT       NOT NULL,
    order_index   INTEGER      NOT NULL,
    field_id      VARCHAR(16)  NOT NULL,
    sense         VARCHAR(20),
    source_photo  VARCHAR(80)  NOT NULL,
    evidence_crop VARCHAR(80),
    observed_on   DATE         NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_route_signs_route FOREIGN KEY (route_id) REFERENCES routes (id) ON DELETE CASCADE,
    CONSTRAINT uq_route_signs_order UNIQUE (route_id, order_index),
    CONSTRAINT uq_route_signs_field UNIQUE (field_id),
    CONSTRAINT ck_route_signs_order CHECK (order_index >= 0),
    CONSTRAINT ck_route_signs_sense CHECK (sense IN ('SUBIENDO', 'BAJANDO'))
);
CREATE INDEX ix_route_signs_route ON route_signs (route_id);

CREATE TABLE route_sign_plates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sign_id    BIGINT      NOT NULL,
    position   INTEGER     NOT NULL,
    template   VARCHAR(20) NOT NULL,
    code       VARCHAR(10),
    background VARCHAR(7),
    foreground VARCHAR(7),
    CONSTRAINT fk_route_sign_plates_sign FOREIGN KEY (sign_id) REFERENCES route_signs (id) ON DELETE CASCADE,
    CONSTRAINT uq_route_sign_plates_pos UNIQUE (sign_id, position),
    CONSTRAINT ck_route_sign_plates_tpl CHECK (template IN ('PLACA_ARCO', 'PLACA_RECT', 'TABLA_FRANJAS')),
    CONSTRAINT ck_route_sign_plates_pos CHECK (position >= 0)
);

-- line_text y line_role llevan prefijo "line_" a proposito: TEXT y ROLE a secas
-- confundirian al leer el SQL junto a los nombres de columna homonimos de otras
-- tablas del esquema.
CREATE TABLE route_sign_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_id    BIGINT      NOT NULL,
    order_index INTEGER     NOT NULL,
    line_text   VARCHAR(60) NOT NULL,
    background  VARCHAR(7),
    foreground  VARCHAR(7),
    line_role   VARCHAR(20),
    CONSTRAINT fk_route_sign_lines_plate FOREIGN KEY (plate_id) REFERENCES route_sign_plates (id) ON DELETE CASCADE,
    CONSTRAINT uq_route_sign_lines_order UNIQUE (plate_id, order_index),
    CONSTRAINT ck_route_sign_lines_order CHECK (order_index >= 0)
);


