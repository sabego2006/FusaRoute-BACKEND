-- ---------------------------------------------------------------------------
-- search_history — una fila por busqueda registrada (RF-07)
-- ---------------------------------------------------------------------------
-- user_id es columna suelta con FK, no una asociacion: la entidad lo mapea con
-- @Column y no con @ManyToOne a proposito (ver el javadoc de
-- SearchHistoryJpaEntity) para no traer el usuario entero en cada lectura.
--
-- ON DELETE CASCADE: el historial no sobrevive al usuario que lo genero. Es dato
-- derivado de su actividad, no un registro contable que haya que conservar.
--
-- No hay tope de filas en la base: lo impone la aplicacion con
-- SpringDataSearchHistoryRepository.deleteOlderBeyond(userId, keep) despues de
-- cada insercion. Un trigger seria mas estricto pero dejaria la regla de negocio
-- partida entre el codigo y el esquema.
CREATE TABLE search_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- 120 es el mismo ancho que users.name y que el length declarado en la
    -- entidad; Hibernate valida el tipo al arrancar, asi que ambos deben
    -- coincidir.
    origin      VARCHAR(120) NOT NULL,
    destination VARCHAR(120) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE search_history IS
    'Ultimas busquedas origen-destino por usuario (RF-07). El tope de filas por usuario lo recorta la aplicacion, no la base.';
COMMENT ON COLUMN search_history.user_id IS
    'Dueno de la busqueda. Sin asociacion JPA: el historial solo necesita el id para filtrar.';
COMMENT ON COLUMN search_history.created_at IS
    'Instante de la busqueda. Ordena el historial y decide que filas se recortan al superar el tope.';


-- Indice que sostiene las dos unicas consultas de la tabla:
--   1. findByUserIdOrderByCreatedAtDesc  -> lee en el orden del indice, sin sort.
--   2. deleteOlderBeyond                 -> su subconsulta ordena por
--      (created_at DESC, id DESC).
-- Por eso la tercera columna es id DESC y no solo (user_id, created_at DESC):
-- cubre el desempate de la subconsulta cuando dos busquedas caen en el mismo
-- instante, que es el caso que esa consulta existe para resolver.
-- El nombre lo cita el javadoc del repositorio; si cambia, actualizarlo alli.
CREATE INDEX ix_search_history_user_created
    ON search_history (user_id, created_at DESC, id DESC);
