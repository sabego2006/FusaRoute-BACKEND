-- V7 — Segundo factor TOTP y codigos de respaldo (SCRUM-179).
--
-- Flyway es el dueno del esquema. V1..V6 ya se aplicaron y NO se tocan: editar
-- una migracion ya aplicada cambia su checksum y rompe el arranque.
--
-- La columna totp_secret guarda el CIPHERTEXT del secreto (AES-256-GCM), nunca
-- el valor en claro. El tamano 255 absorbe el nonce (12 bytes) + ciphertext +
-- tag (16 bytes) codificados en Base64 incluso para secretos Base32 largos.
--
-- totp_enabled por defecto FALSE: los usuarios existentes quedan sin TOTP, y en
-- su proximo login el backend emite el token de enrolamiento para forzar el
-- enrolamiento (TOTP obligatorio).


ALTER TABLE users
    ADD COLUMN totp_secret  VARCHAR(255),
    ADD COLUMN totp_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    -- Un usuario con TOTP activo DEBE tener secreto; sin secreto se rompe el
    -- login en el adaptador. Mejor que la base lo prohiba.
    ADD CONSTRAINT ck_users_totp_consistency CHECK (
        totp_enabled = FALSE OR totp_secret IS NOT NULL
    );

COMMENT ON COLUMN users.totp_secret IS
    'Ciphertext Base64 (AES-256-GCM) del secreto TOTP. NUNCA se guarda en claro. NULL si el usuario no ha iniciado el enrolamiento.';
COMMENT ON COLUMN users.totp_enabled IS
    'TRUE cuando el usuario ya confirmo el primer codigo valido. Hasta entonces el secreto puede existir pero no es exigible al login.';


-- ---------------------------------------------------------------------------
-- user_recovery_codes — codigos de respaldo del segundo factor (SCRUM-179)
-- ---------------------------------------------------------------------------
-- Son la unica salida ante perdida del telefono mientras RF-recuperacion este
-- fuera de alcance. Cada codigo se consume una sola vez (used = TRUE) y se
-- guarda hasheado con BCrypt — el usuario los ve una sola vez al confirmar el
-- enrolamiento. ON DELETE CASCADE: si se borra el usuario, se van con el.
CREATE TABLE user_recovery_codes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- BCrypt produce 60 caracteres; 72 deja el mismo colchon que password_hash.
    code_hash  VARCHAR(72)  NOT NULL,
    used       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- La busqueda del login barre los activos del usuario para encajar el codigo.
CREATE INDEX ix_recovery_codes_user ON user_recovery_codes (user_id);

COMMENT ON TABLE user_recovery_codes IS
    'Codigo de respaldo del segundo factor. Un solo uso. Hash BCrypt — nunca en claro.';
