-- Solo entran los lugares con coordenada (135); los que P0 dejo sin coordenada no se pueden
-- buscar por geometria y se agregan en una migracion nueva cuando alguien aporte el dato.
--
-- name_normalized y alias_normalized siguen la misma regla que PlaceName.normalize del dominio (NFD sin
-- diacriticos, minusculas, sin puntos, espacios colapsados) y son UNIQUE entre si por separado; el
-- generador ademas garantiza que ningun alias choque con el nombre de otro lugar. route_neighborhoods NO
-- se toca: sigue siendo lo que se muestra en "Por donde pasa".
CREATE TABLE places (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            VARCHAR(120)     NOT NULL,
    name            VARCHAR(140)     NOT NULL,
    name_normalized VARCHAR(140)     NOT NULL,
    lat             DOUBLE PRECISION NOT NULL,
    lng             DOUBLE PRECISION NOT NULL,
    created_at      TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT uq_places_slug UNIQUE (slug),
    CONSTRAINT uq_places_name_normalized UNIQUE (name_normalized),
    CONSTRAINT ck_places_lat CHECK (lat BETWEEN -90 AND 90),
    CONSTRAINT ck_places_lng CHECK (lng BETWEEN -180 AND 180)
);

CREATE TABLE place_aliases (
    place_id         BIGINT       NOT NULL,
    alias            VARCHAR(140) NOT NULL,
    alias_normalized VARCHAR(140) NOT NULL,
    PRIMARY KEY (place_id, alias_normalized),
    CONSTRAINT uq_place_aliases_alias_normalized UNIQUE (alias_normalized),
    CONSTRAINT fk_place_aliases_place FOREIGN KEY (place_id) REFERENCES places (id) ON DELETE CASCADE
);

